# -*- coding: utf-8 -*-
"""Indexes what the hangar look recipes may reference in one client build (hangars/client_<version>.json).

The recipes (hangars/looks/<id>/recipe.json) name texture paths and environment parameters of the player's own client;
the manager applies them on the player's PC (docs/specs/2026-10-06-custom-hangars.md §5.2). This tool reads an
installed client's packages (read only) and writes the names it finds: the texture paths under TEXTURE_PREFIXES and,
for every space a recipe bases on, each environment's parameter paths with their value types. Names only: no file
content of the client is copied. tools/build/tests/test_hangar_recipes.py checks every recipe against the index.

    python tools/build/client_index.py "D:/Games/Tanki"    # rewrite hangars/client_<version>.json
"""
from __future__ import absolute_import, division, print_function, unicode_literals

import io
import os
import re
import sys
import zipfile
from xml.etree import ElementTree

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import fileio  # noqa: E402
import hangars  # noqa: E402
import packed_xml  # noqa: E402

TEXTURE_PREFIXES = ('maps/skyboxes/', 'maps/fx/', 'system/maps/')
TEXTURE_EXTENSION = '.dds'
VERSION_PATTERN = re.compile(r'v\.(\d+\.\d+\.\d+\.\d+)')
ENVIRONMENTS_XML = '%s/environments/environments.xml'
ENVIRONMENT_XML = '%s/environments/%s/environment.xml'
KIND_NAMES = {
    packed_xml.STRING: 'string',
    packed_xml.INT: 'int',
    packed_xml.BOOL: 'bool',
    packed_xml.BLOB: 'blob',
}


def client_version(game_dir):
    with io.open(os.path.join(game_dir, 'version.xml'), encoding='utf-8') as handle:
        match = VERSION_PATTERN.search(handle.read())
    if not match:
        raise SystemExit('no client version in version.xml')
    return match.group(1)


def package_paths(game_dir):
    """The packages of paths.xml in the order the client mounts them."""
    root = ElementTree.parse(os.path.join(game_dir, 'paths.xml')).getroot()
    listed = [element.text.strip() for element in root.iter('Package') if element.text]
    return [os.path.normpath(os.path.join(game_dir, path)) for path in listed]


class Packages(object):

    def __init__(self, paths):
        self.archives = [zipfile.ZipFile(path) for path in paths if os.path.isfile(path)]

    def names(self):
        for archive in self.archives:
            for name in archive.namelist():
                yield name

    def read(self, path):
        wanted = path.lower()
        for archive in self.archives:
            for info in archive.infolist():
                if info.filename.lower() == wanted:
                    return archive.read(info)
        return None


def textures(packages):
    found = set()
    for name in packages.names():
        lowered = name.lower()
        if lowered.endswith(TEXTURE_EXTENSION) and lowered.startswith(TEXTURE_PREFIXES):
            found.add(name)
    return sorted(found)


def kind_name(node):
    if node.kind == packed_xml.FLOATS:
        return 'floats:%d' % len(node.value)
    return KIND_NAMES[node.kind]


def environment_leaves(packages, space, guid):
    data = packages.read(ENVIRONMENT_XML % (space, guid.replace('.', '-')))
    if data is None:
        return None, {}
    root = packed_xml.decode(data)
    name = root.child('name')
    return (name.value if name else None), {path: kind_name(node) for path, node in packed_xml.leaves(root)}


def space_environments(packages, space):
    data = packages.read(ENVIRONMENTS_XML % space)
    if data is None:
        return {}
    root = packed_xml.decode(data)
    found = {}
    for entry in root.children:
        if entry.name != 'environment':
            continue
        name, leaves = environment_leaves(packages, space, entry.value.strip())
        if name:
            found[name] = leaves
    return found


def build_index(game_dir):
    packages = Packages(package_paths(game_dir))
    spaces = sorted(set(recipe['base']['space'] for recipe in hangars.load_recipes()))
    return {
        '$comment': 'Generated by tools/build/client_index.py from an installed client: names only, no content.',
        'client': client_version(game_dir),
        'textures': textures(packages),
        'environments': {space: space_environments(packages, space) for space in spaces},
    }


def main(argv):
    if not argv:
        raise SystemExit(__doc__)
    index = build_index(argv[0])
    path = hangars.client_index_path(index['client'])
    fileio.write_json(path, index, True)
    print('Wrote %s (%d textures)' % (path, len(index['textures'])))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
